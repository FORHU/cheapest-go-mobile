final List<({String code, String label})> countryOptions = () {
  final options = [for (final e in _names.entries) (code: e.key, label: '${e.value} (${e.key})')];
  options.sort((a, b) {
    if (a.code == 'PH') return -1;
    if (b.code == 'PH') return 1;
    return a.label.compareTo(b.label);
  });
  return options;
}();

